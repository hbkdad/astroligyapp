function placement(
  body: CelestialBody,
  longitude: number,
  latitude: number,
  speed: number,
  sign: ZodiacSign,
  signIndex: number,
  degreeWithinSign: number,
  houseNumber: number,
): NatalPlacement {
  return {
    body,
    eclipticLongitudeDegrees: longitude,
    eclipticLatitudeDegrees: latitude,
    speedLongitudeDegreesPerDay: speed,
    zodiac: {
      longitudeDegrees: longitude,
      signIndex,
      sign,
      degreeWithinSign,
    },
    houseNumber,
  };
}

function aspect(
  firstBody: CelestialBody,
  secondBody: CelestialBody,
  type: AspectType,
  actualAngleDegrees: number,
  orbDegrees: number,
  maximumOrbDegrees: number,
  phase: AspectPhase,
  normalizedStrength: number,
): NatalAspect {
  return {
    firstBody,
    secondBody,
    type,
    exactAngleDegrees: DEFAULT_ASPECT_DEFINITIONS.find(
      (definition) => definition.type === type,
    )!.exactAngleDegrees,
    actualAngleDegrees,
    orbDegrees,
    maximumOrbDegrees,
    phase,
    normalizedStrength,
  };
}

